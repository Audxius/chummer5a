#!/usr/bin/env bash
# Regenerates Chummer.Desktop/Theme/Icons.axaml (StreamGeometry resources "Icon.<Key>") and the icon credits
# from tools/native/icons.txt, downloading the SVGs from the game-icons.net GitHub repository.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/../../Chummer.Desktop/Theme/Icons.axaml"
credits="$here/../../Chummer.Desktop/Assets/ICONS-CREDITS.md"
mkdir -p "$(dirname "$credits")"
{
  echo '<!-- Generated by tools/native/fetch-icons.sh from tools/native/icons.txt. Do not edit by hand. -->'
  echo '<!-- Icons by game-icons.net contributors, CC BY 3.0 (https://creativecommons.org/licenses/by/3.0/). -->'
  echo '<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">'
} > "$out"
{
  echo '# Icon credits'
  echo
  echo 'Icons from [game-icons.net](https://game-icons.net), licensed [CC BY 3.0](https://creativecommons.org/licenses/by/3.0/):'
  echo
} > "$credits"
grep -vE '^\s*(#|$)' "$here/icons.txt" | while IFS='=' read -r key path; do
  svg=$(curl -fsSL "https://raw.githubusercontent.com/game-icons/icons/master/$path.svg")
  # The glyph is the path filled white (the first path is the black 512x512 background square).
  d=$(printf '%s' "$svg" | grep -oE '<path fill="#fff" d="[^"]+"' | head -1 | sed -E 's/.* d="//; s/"$//')
  if [ -z "$d" ]; then echo "no glyph path in $path" >&2; exit 1; fi
  printf '  <StreamGeometry x:Key="Icon.%s">%s</StreamGeometry>\n' "$key" "$d" >> "$out"
  author=${path%%/*}; name=${path#*/}
  printf -- '- `Icon.%s`: [%s](https://game-icons.net/1x1/%s/%s.html) by %s\n' "$key" "$name" "$author" "$name" "$author" >> "$credits"
done
echo '</ResourceDictionary>' >> "$out"
echo "wrote $(grep -c StreamGeometry "$out") icons"
